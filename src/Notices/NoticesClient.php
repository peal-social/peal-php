     *
     * Example:
     * ```php
     * $client->notices->markRead(
     *     new MarkNoticesRead([
     *         'ids' => [
     *             'ids',
     *         ],
     *     ]),
     * );
     * ```
     *
     * @param MarkNoticesRead $request
     * @param ?array{
     *   baseUrl?: string,
     *   maxRetries?: int,
     *   timeout?: float,
     *   headers?: array<string, string>,
     *   queryParameters?: array<string, mixed>,
     *   bodyProperties?: array<string, mixed>,
     * } $options
